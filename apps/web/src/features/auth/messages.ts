export function authMessage(code: string, kk: boolean) {
  const messages: Record<string, [string, string]> = {
    AUTH_REQUIRED: ['Войдите в аккаунт.', 'Тіркелгіге кіріңіз.'],
    INVALID_CREDENTIALS: ['Неверная почта или пароль.', 'Пошта немесе құпиясөз қате.'],
    EMAIL_IN_USE: ['Эта почта уже зарегистрирована.', 'Бұл пошта тіркелген.'],
    INVALID_INVITATION: [
      'Ссылка истекла, отозвана или уже использована.',
      'Сілтеменің мерзімі аяқталған, күші жойылған немесе қолданылған.',
    ],
    FORBIDDEN: ['У вас нет доступа к этому разделу.', 'Бұл бөлімге кіруге рұқсатыңыз жоқ.'],
    TRY_LATER: [
      'Слишком много попыток. Повторите через 15 минут.',
      'Әрекет саны тым көп. 15 минуттан кейін қайталаңыз.',
    ],
  };
  return (
    messages[code]?.[kk ? 1 : 0] ??
    (kk
      ? 'Әрекетті орындау мүмкін болмады. Деректерді тексеріп, қайталаңыз.'
      : 'Не удалось выполнить действие. Проверьте данные и повторите.')
  );
}
